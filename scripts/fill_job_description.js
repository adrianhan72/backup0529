// ── 담당업무 결정 함수 ────────────────────────────────────────────
function resolveJob(emp, industry) {
  const dept = (emp.department || '').trim();
  const pos  = (emp.position   || '').trim();
  const cat  = (emp.employment_category || '').trim();

  let job = '';

  // ─ STEP 1) 부서+업종 키로 테이블 조회
  if (dept) {
    const tableKey = `${dept}|${industry}`;
    const entry = JOB_TABLE[tableKey];
    if (entry) {
      job = (pos && entry[pos]) ? entry[pos] : (entry['_'] || '');
    }
  }

  // ─ STEP 2) 테이블 미등록 시 부서 키워드 범용 추론
  if (!job && dept) {
    if      (dept.includes('개발'))        job = '소프트웨어 개발 및 유지보수';
    else if (dept.includes('기획'))        job = '사업 기획 및 전략 수립';
    else if (dept.includes('경영지원'))    job = '경영 지원 및 행정 업무';
    else if (dept.includes('영업'))        job = '영업 및 고객 관리';
    else if (dept.includes('마케팅'))      job = '마케팅 기획 및 홍보';
    else if (dept.includes('디자인'))      job = '디자인 기획 및 제작';
    else if (dept.includes('인사'))        job = '인사 관리 및 채용 운영';
    else if (dept.includes('총무'))        job = '총무 및 시설 관리';
    else if (dept.includes('생산'))        job = '생산 공정 작업';
    else if (dept.includes('공사'))        job = '건설 현장 업무';
    else if (dept.includes('안전'))        job = '안전 관리 업무';
    else if (dept.includes('물류'))        job = '물류 운영 업무';
    else if (dept.includes('관리'))        job = '관리 업무';
    else if (dept.includes('연구'))        job = '연구 개발 업무';
    else if (dept.includes('고객'))        job = '고객 지원 업무';
    else if (dept.includes('에너지'))      job = '에너지 설비 운영 업무';
    else if (dept.includes('태양광'))      job = '태양광 사업 운영 업무';
    else                                   job = `${dept} 관련 업무`;
  }

  // ─ STEP 3) 부서 없을 때 업종+직책 조합으로 처리
  if (!job) {
    // 직책+업종 조합 키 조회
    const posKey = pos ? `${industry}|${pos}` : null;
    if (posKey && INDUSTRY_POSITION_DEFAULT[posKey]) {
      job = INDUSTRY_POSITION_DEFAULT[posKey];
    }
  }

  // ─ STEP 4) 최종 폴백 — 업종 기본값
  if (!job) {
    job = INDUSTRY_DEFAULT[industry] || '회사가 지정하는 업무';
  }

  // ─ 고용형태 접두어 적용
  const prefix = CAT_PREFIX[cat] || '';
  return prefix + job;
}

// ── 실행 ─────────────────────────────────────────────────────────
const db        = JSON.parse(fs.readFileSync(DB_PATH, 'utf8'));
const employees = db.employees || [];

let fixedCount = 0;
let skipCount  = 0;
const log = [];

employees.forEach(emp => {
  if (emp.job_description && emp.job_description.trim()) {
    skipCount++;
    return;
  }
  const industry = COMPANY_INDUSTRY[emp.company_id] || '서비스';
  const job      = resolveJob(emp, industry);
  emp.job_description = job;
  log.push({
    id:       emp.id,
    name:     emp.name,
    company:  emp.company_id,
    cat:      emp.employment_category || '-',
    dept:     emp.department  || '-',
    pos:      emp.position    || '-',
    industry,
    job,
  });
  fixedCount++;
});

fs.writeFileSync(DB_PATH, JSON.stringify(db, null, 2), 'utf8');

