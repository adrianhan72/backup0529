// 구형 데이터(2024 이하)는 dep1만 있으므로 dep2~dep7, extra_per_dep는 0
function convertToDBRows(year, rows) {
  return rows.map((row, idx) => ({
    id: `tax_${year}_${String(idx).padStart(3, '0')}`,
    year,
    from_amount: row[0],
    to_amount: row[1],
    dep1_tax: row[2] || 0,
    dep2_tax: row.length > 3 ? (row[3] || 0) : 0,
    dep3_tax: row.length > 4 ? (row[4] || 0) : 0,
    dep4_tax: row.length > 5 ? (row[5] || 0) : 0,
    dep5_tax: row.length > 6 ? (row[6] || 0) : 0,
    dep6_tax: row.length > 7 ? (row[7] || 0) : 0,
    dep7_tax: row.length > 8 ? (row[8] || 0) : 0,
    extra_per_dep: row.length > 9 ? (row[9] || 0) : 0,
    created_at: now,
    updated_at: now,
  }));
}

